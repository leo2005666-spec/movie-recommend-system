async function main() {
  const { init, getDb, save } = require(path.join(__dirname, '../src/db/db'));
  await init();
  const db = getDb();

  const clearFirst = process.argv.includes('--clear');
  if (clearFirst) {
    console.log('🧹 清空旧评论...');
    await db.exec('DELETE FROM comments');
    console.log('   已清空');
  }

  // 获取所有电影和用户
  const movies = await db.prepare('SELECT id, title, director, actors FROM movies').all();
  const users = await db.prepare('SELECT id, username FROM users').all();
  const userIds = users.map(u => u.id);

  if (movies.length === 0) {
    console.log('❌ 没有电影数据，请先运行爬虫获取电影');
    return;
  }
  if (userIds.length < 3) {
    console.log('❌ 用户太少（需要至少3个），请先创建演示用户');
    return;
  }

  console.log(`🎬 ${movies.length} 部电影, ${userIds.length} 个用户\n`);

  let totalRoots = 0;
  let totalReplies = 0;

  for (const movie of movies) {
    // 查找定制评论
    let movieReviews = null;
    for (const mr of MOVIE_REVIEWS) {
      if (mr.titlePattern.test(movie.title)) {
        movieReviews = mr.reviews;
        break;
      }
    }

    // 无定制评论则用通用评论
    const pool = movieReviews || GENERIC_REVIEWS;

    // 每部电影生成 5-15 条根评论
    const rootCount = 4 + (movie.id % 10);
    const shuffledUsers = [...userIds].sort(() => Math.random() - 0.5);

    for (let i = 0; i < rootCount && i < pool.length; i++) {
      const uid = shuffledUsers[i % shuffledUsers.length];
      const review = pool[i % pool.length];
      const username = users.find(u => u.id === uid)?.username || '匿名';

      // 如果有电影信息，尝试在评论中插入具体的演员/导演名字（增强真实感）
      let content = review.content;

      await db.prepare(
        'INSERT INTO comments (user_id, movie_id, parent_id, reply_to_user_id, content, images) VALUES (?, ?, NULL, NULL, ?, NULL)'
      ).run(uid, movie.id, content);

      const ridRow = await db.prepare('SELECT last_insert_rowid() as id').get();
      const rootId = ridRow?.id;
      if (!rootId) continue;
      totalRoots += 1;

      // 30% 的根评论获得 1-3 条回复
      if (Math.random() < 0.3) {
        const replyCount = 1 + Math.floor(Math.random() * 3);
        let lastReplyUserId = uid;
        for (let j = 0; j < replyCount; j++) {
          const ruid = shuffledUsers[(i + j + 1) % shuffledUsers.length];
          const rcontent = REPLY_TEMPLATES[(i * 3 + j) % REPLY_TEMPLATES.length];
          await db.prepare(
            'INSERT INTO comments (user_id, movie_id, parent_id, reply_to_user_id, content, images) VALUES (?, ?, ?, ?, ?, NULL)'
          ).run(ruid, movie.id, rootId, lastReplyUserId, rcontent);
          lastReplyUserId = ruid;
          totalReplies += 1;
        }
      }
    }
  }

  save();
  console.log(`\n✅ 完成：生成 ${totalRoots} 条根评论 + ${totalReplies} 条回复`);
  console.log('   数据库已保存');
}

main().catch(e => { console.error(e); process.exit(1); });
